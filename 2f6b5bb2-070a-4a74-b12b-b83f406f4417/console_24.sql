select :n,
       :n % 88,
       (:n % 88) % 12,

       case
           when (:n % 88) % 12 in (2, 5, 7, 10) then 'black'
           else 'white' end as res
create table training.piano (n int4, res text)
alter table training.piano add constraint piano_pk primary key (n) generated by default as identity
