                    where true
                    union all
                    select ca.id, ca.parent, lst||ca.id
                    from training.categories ca
                             join total on ca.id = total.parent)
select id, array_agg(DISTINCT elem ORDER BY elem) FROM total, unnest(lst) AS elem
group by id

$$;

