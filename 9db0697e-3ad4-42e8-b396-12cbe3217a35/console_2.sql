drop function if exists loader.add_files_to_process(int4, text, text);

create or replace function loader.add_files_to_process(in_date_id integer, in_files text, in_node_name text)
    returns integer
    language plpgsql
as
$function$
declare
    l_row_cnt int4;
    l_load_id int;
    l_step_id int;
    l_eod_ts  time;
begin
    select nextval('public.load_timing_seq') into l_load_id;
    l_step_id := 1;

    select public.load_log(l_load_id, l_step_id, 'add_files_to_process STARTED ===', 0, 'O')
    into l_step_id;

    insert into loader.files (file_name, date_id, node_name)
        (select unnest(in_files::text[]) as filename,
                in_date_id               as date_id,
                in_node_name)
    on conflict (file_name, date_id, node_name) do nothing;
    get diagnostics l_row_cnt = row_count;

    if l_row_cnt > 0 then
        select public.load_log(l_load_id, l_step_id, 'add_files_to_process files added', l_row_cnt, 'A')
        into l_step_id;
    end if;

    select setting_value::time
    into l_eod_ts
    from loader.setting
    where setting_name = 'end_of_day_time';

    drop table if exists tmp_files;
    create temp table if not exists tmp_files as
    select *
    from loader.files
    where date_id = in_date_id
      and node_name = in_node_name;

    insert
    into loader.daily_load (date_id, file_id)
        -- for new files
        (select tfl.date_id, tfl.file_id
         from tmp_files tfl
         where not exists(select 1
                          from loader.daily_load dl
                          where dl.date_id = tfl.date_id
                            and dl.file_id = tfl.file_id))
    union
    -- for
    (select tfl.date_id, tfl.file_id
     from tmp_files tfl
     where exists(select 1
                  from loader.daily_load dl
                  where dl.date_id = tfl.date_id
                    and dl.file_id = tfl.file_id
                    and (dl.loading_status = 'E' or end_position is not null))
       and not exists(select 1
                      from loader.daily_load dl
                      where dl.date_id = tfl.date_id
                        and dl.file_id = tfl.file_id
                        and dl.loading_status != 'E'
                        and end_position is null)
       and not exists(select 1
                      from loader.daily_load dl
                      where dl.date_id = tfl.date_id
                        and dl.file_id = tfl.file_id
                        and dl.start_processing >=
                            to_date(dl.date_id::text, 'YYYYMMDD') + l_eod_ts));

    get diagnostics l_row_cnt = row_count;

    if l_row_cnt > 0 then
        select public.load_log(l_load_id, l_step_id, 'add_files_to_process daily_load added', l_row_cnt, 'A')
        into l_step_id;

    end if;
    return l_row_cnt;
end;
$function$
;


drop function if exists loader.choose_next_file(int4, text, bool);

create or replace function loader.choose_next_file(in_date_id integer, in_node_name text,
                                                   in_is_only_show boolean default true)
    returns table
            (
                file_id        integer,
                file_name      text,
                start_position integer,
                batch_id       integer
            )
    language plpgsql
as
$function$
declare
    l_load_id        int;
    l_step_id        int;
    l_start_position int4;
    l_batch_id       int4;
    l_file_id        int4;
    l_eod_ts         time;

begin
    select nextval('load_timing_seq') into l_load_id;
    l_step_id := 1;


    select public.load_log(l_load_id, l_step_id, 'choose_next_file for ' || in_node_name || ' STARTED ===', 0, 'O')
    into l_step_id;

    select setting_value::time
    into l_eod_ts
    from loader.setting
    where setting_name = 'end_of_day_time';

    select dl.batch_id, dl.file_id
    into l_batch_id, l_file_id
    from loader.daily_load dl
             join loader.files fl using (file_id, date_id)
    where dl.date_id = in_date_id
      and fl.node_name = in_node_name
      and dl.loading_status = 'A'
    order by dl.db_create_time
    limit 1 for update skip locked;

    if l_batch_id is not null then
        -- start position
        select end_position
        into l_start_position
        from loader.daily_load dl
        where dl.date_id = in_date_id
          and dl.file_id = l_file_id
          and dl.loading_status != 'R'
        order by dl.end_position desc nulls last
        limit 1;

        if not in_is_only_show then
            update loader.daily_load dl
            set loading_status   = 'M',
                start_position   = coalesce(l_start_position, 0) + 1,
                start_processing = clock_timestamp()
            where dl.batch_id = l_batch_id;
        end if;

        return query
            select l_file_id, fl.file_name, coalesce(l_start_position, 0), l_batch_id
            from loader.files fl
            where fl.file_id = l_file_id;

        select public.load_log(l_load_id, l_step_id,
                               'chosen file for ' || in_node_name || ' is - ' ||
                               coalesce(l_file_id::text, 'no files') || '. COMPLETED ===',
                               0, 'F')
        into l_step_id;
    end if;

end ;
$function$
;

