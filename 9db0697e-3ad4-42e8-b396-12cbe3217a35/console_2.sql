create table if not exists loader.files
(
    file_id        int4
        constraint files_pk primary key generated by default as identity not null,
    file_name      text                                                  not null,
    date_id        int4                                                  not null,
    node_name      text                                                  not null,
    db_create_time timestamp default clock_timestamp()                   not null,
    constraint files_file_name_date_id_unq unique (file_name, date_id, node_name)
);
create index files_date_id_node_name_idx on loader.files using btree (date_id, node_name);


create table if not exists loader.daily_load
(
    batch_id          int4                                not null
        constraint daily_load_pk primary key generated by default as identity,
    date_id           int4                                not null,
    file_id           int4                                not null
        constraint daily_load_files_fk references loader.files (file_id),
    start_position    int4                                null,
    end_position      int4                                null,
    start_processing  timestamp                           null,
    end_processing    timestamp                           null,
    loaded_rows       int4                                null,
    loading_status    bpchar    default 'A'::bpchar       not null,
    loading_confirmed bool      default false             not null,
    db_create_time    timestamp default clock_timestamp() not null
);
